    data = build()
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)

    print("=" * 72)
    print("  Сборка датасета из снимков официальных страниц ИГУ")
    print("=" * 72)
