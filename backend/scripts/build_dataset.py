# Код направления бывает и отдельной строкой, и слитно с названием
# («38.03.01 Экономика») — вёрстка таблицы в PDF не единообразна.
CODE_RE = re.compile(r"^(\d{2}\.\d{2}\.\d{2})\s*(.*)$")
FORMS = {"Очная": "очная", "Заочная": "заочная", "Очно-заочная": "очно-заочная"}
