-- Публичное расписание: то же, что schedule_calendar, но без ФИО.
--
-- Применять:
--   python backend/scripts/apply_sql.py backend/sql/018_public_schedule.sql --apply
--
-- ---------------------------------------------------------------------
-- ЗАЧЕМ
-- ---------------------------------------------------------------------
--
-- Встраиваемый виджет работает под ролью `guest`, токен которой выдаётся БЕЗ
-- ПАРОЛЯ любому посетителю сайта. Расписание — самый частый вопрос на сайте
-- вуза, и вузы его публикуют открыто, поэтому закрывать его целиком незачем.
--
-- Но schedule_calendar содержит teacher_name. Одно дело — опубликованное
-- расписание занятий, другое — возможность у анонимного посетителя спросить,
-- где конкретный преподаватель находится в 14:00 в четверг. Для вопросов
-- абитуриента и студента ФИО не нужны вовсе, поэтому здесь их просто нет:
-- не «модель попросили не выбирать колонку», а колонки не существует.
--
-- Сотрудники продолжают пользоваться schedule_calendar со всеми полями —
-- у них вход по паролю и роль в подписанном токене.
--
-- Отменённые занятия (миграция 010) сюда не попадают: посетителю нужно
-- расписание, а не история изменений.

DROP VIEW IF EXISTS assistant.public_schedule;

CREATE VIEW assistant.public_schedule AS
SELECT
    lesson_date,
    weekday,
    pair_number,
    starts_at,
    ends_at,
    week_type,
    lesson_type,
    subject_name,
    group_name,
    course,
    program_name,
    building,
    room_number,
    academic_year,
    term_name
FROM assistant.schedule_calendar;

-- Подпись попадает в промпт модели (ai_agent.fetch_object_comments), поэтому
-- упоминать в ней имя объекта, недоступного этой роли, НЕЛЬЗЯ: гость увидит
-- название и попробует им воспользоваться. На этом уже обожглись — первая
-- редакция подписи говорила «сотрудникам доступен schedule_calendar», и
-- модель послушно строила запрос к нему, получая отказ проверки.
COMMENT ON VIEW assistant.public_schedule IS
    'Строка = одно занятие. Расписание занятий: дата, пара, время, дисциплина, '
    'группа, корпус и аудитория. ФИО преподавателей здесь нет. '
    'Корпус в building записан полным названием («Главный корпус», '
    '«Лабораторный корпус») — сравнивай через ILIKE, а не знаком равенства.';

-- Номер аудитории повторяется в разных корпусах: «201» есть и в главном, и в
-- лабораторном. Без корпуса вопрос «сколько мест в аудитории 201» отвечается
-- тремя разными числами — так и было до этой подписи.
COMMENT ON TABLE assistant.rooms IS
    'Строка = одна аудитория. Ключ — ПАРА «корпус + номер»: аудитория 201 есть '
    'в четырёх корпусах и вмещает от 25 до 150 человек, поэтому фильтровать '
    'только по number нельзя — получится несколько разных ответов. Корпус '
    'задавай буквой через building_code (А, Б, В, Л) либо ILIKE по building: '
    'там полные названия («Главный корпус»), и точное сравнение с '
    '«главный корпус» не совпадёт ни с чем.';
