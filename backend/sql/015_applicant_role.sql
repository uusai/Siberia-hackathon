-- Роль абитуриента.
--
-- Применять:
--   python backend/scripts/apply_sql.py backend/sql/015_applicant_role.sql --apply
--
-- ЗАЧЕМ. Регламент прав (user_right.md) выделяет абитуриента в отдельную
-- категорию пользователей со своим набором сведений: направления, места,
-- сроки, проходные баллы прошлых лет и агрегированная статистика приёма.
-- До сих пор отдельной роли не было — абитуриент заходил под учёткой
-- студента, и это записано прямым текстом в комментарии security.py.
--
-- ЧЕМ ЭТО ПЛОХО БЫЛО. Абитуриенту доставалось лишнее: расписание занятий,
-- учебные планы групп, загруженность аудиторий, список преподавателей — всё,
-- что видит студент. Обратно тоже неверно: агрегированная статистика приёма
-- за прошлые годы (admission_dynamics) была закрыта администрацией, хотя
-- регламент отдаёт её именно абитуриенту.
--
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ. Раскладку таблиц по ролям она не трогает —
-- та живёт в backend/app/security.py (ALLOWED_TABLES_BY_ROLE). Здесь только
-- одно: база перестаёт отвергать значение 'applicant' в auth.users.role.
--
-- ПРО users_person_link_ck. Второй констрейнт таблицы менять не нужно: он
-- требует, чтобы student_id заполнялся только у роли student, а teacher_id —
-- только у teacher. У абитуриента оба поля пусты, и условие выполняется само.
-- Личных представлений (my_*) у этой роли нет: человека, который ещё не
-- поступил, в assistant.students не существует.

ALTER TABLE auth.users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE auth.users ADD CONSTRAINT users_role_check CHECK (
    role IN ('applicant', 'student', 'teacher', 'deans-office', 'administration')
);
