-- Аналитика пользовательских запросов — через самого ассистента.
--
-- Применять:
--   python backend/scripts/apply_sql.py backend/sql/023_request_analytics.sql --apply
--
-- ---------------------------------------------------------------------
-- ЗАЧЕМ
-- ---------------------------------------------------------------------
--
-- «Возможность аналитики пользовательских запросов через ИИ» — обязательное
-- архитектурное требование памятки. Журнал у нас пишется с самого начала
-- (assistant.audit_log), и есть отчёт GET /meta/stats — но это ГОТОВЫЙ отчёт
-- на заранее написанном SQL. Спросить систему своими словами — «сколько
-- запросов отклонено за сутки», «какие вопросы чаще всего не находят
-- данных», «под какой ролью дольше всего думает модель» — было нельзя:
-- audit_log в whitelist не входит.
--
-- Открываем не саму таблицу, а обезличенный срез.
--
-- ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ:
--   - username. На стенде это четыре демо-учётки, но в реальном вузе —
--     живые люди, и «кто что спрашивал» превращает журнал качества в слежку.
--     Для аналитики ЗАПРОСОВ имя спрашивавшего не нужно: нужны роль, исход
--     и время;
--   - generated_sql и executed_sql. Это внутренние тексты запросов; в
--     аналитике они дают шум, а в ответе пользователю — тем более.
--     Разбираться в конкретном запросе идут в саму таблицу, а не через чат.
--
-- Роль: только администрация (_ANALYTICS_ADMIN в security.py). Деканату и
-- преподавателю журнал обращений не адресован.

DROP VIEW IF EXISTS assistant.request_log;

CREATE VIEW assistant.request_log AS
SELECT
    ts                                          AS asked_at,
    ts::date                                    AS asked_on,
    role                                        AS asked_by_role,
    question,
    verdict,
    reject_reason,
    row_count,
    duration_ms,
    llm_ms,
    -- Сколько времени ушло НЕ в модель: разбор, проверка и сама база.
    greatest(duration_ms - coalesce(llm_ms, 0), 0) AS db_ms,
    model
FROM assistant.audit_log
-- Исходы входа (login_ok, login_failed, login_throttled) — это не запросы
-- пользователя к данным, а события авторизации. Они остаются в audit_log и
-- в /meta/stats, но в аналитике ВОПРОСОВ только мешают: у них нет ни
-- вопроса, ни строк, ни SQL.
WHERE verdict NOT LIKE 'login_%';

COMMENT ON VIEW assistant.request_log IS
    'Строка = ОДНО обращение к ассистенту. Журнал вопросов без имени '
    'спрашивавшего и без текста SQL. verdict: ok — ответ отдан, rejected — '
    'отклонено проверкой безопасности, empty — данных не нашлось, '
    'out_of_scope — вопрос вне области, db_error — СУБД не выполнила запрос, '
    'placeholder — модель выдала бланк вместо ответа, no_sql — вопрос не '
    'распознан. duration_ms — весь путь, llm_ms — из него в модели.';
