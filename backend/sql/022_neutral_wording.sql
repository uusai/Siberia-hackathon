-- Нейтральные формулировки в текстах, которые видит пользователь.
--
-- Применять:
--   python backend/scripts/apply_sql.py backend/sql/022_neutral_wording.sql --apply
--
-- ---------------------------------------------------------------------
-- ЗАЧЕМ
-- ---------------------------------------------------------------------
--
-- Ассистент отвечает ПО БАЗЕ ДАННЫХ, а не по сайту, с которого её однажды
-- наполнили. Колонки происхождения (source_url, data_status и прочие) от
-- модели уже скрыты — см. ai_agent._PROVENANCE_COLUMNS. Осталось шесть
-- текстов, где название конкретного вуза и отсылки наружу зашиты прямо в
-- данные и потому доезжают до ответа.
--
-- Правится ТОЛЬКО формулировка. Ни одна цифра, дата и ни одно название
-- подразделения не меняются: «Институт математики и информационных
-- технологий» — это содержимое каталога, а не брендинг. Переименовать их
-- значило бы превратить настоящие данные в выдумку.
--
-- Отдельно про «уточняйте на официальном сайте» в описании общежитий: это
-- прямое нарушение правила 6 интерпретирующего промпта («не отправляй
-- пользователя никуда за ответом»). Промпт запрещал модели такие отсылки, а
-- сами данные их содержали — и модель добросовестно их пересказывала.

UPDATE assistant.faq_entries
SET answer = replace(answer, 'ИГУ самостоятельно проводит',
                             'Университет самостоятельно проводит')
WHERE answer LIKE '%ИГУ самостоятельно проводит%';

UPDATE assistant.faq_entries
SET question = 'Какие факультеты и институты есть в университете?'
WHERE question = 'Какие факультеты и институты есть в ИГУ?';

UPDATE assistant.dormitories
SET name = 'Общежития университета',
    description = 'Университет предоставляет общежития. Информация о '
                  'количестве мест публикуется не позднее 1 июня 2026 года '
                  '(Правила приёма, п. 3). Точное количество мест, адреса и '
                  'условия заселения на текущий год в базе пока не заполнены.'
WHERE name = 'Общежития ИГУ';

UPDATE assistant.contacts
SET title = 'Центральная приёмная комиссия'
WHERE title = 'Центральная приёмная комиссия ИГУ';

